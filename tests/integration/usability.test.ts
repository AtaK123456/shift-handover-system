import { test } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import request from "supertest";
import jwt from "jsonwebtoken";
import { createPrismaClient } from "../../src/database.js";
import { createApp } from "../../src/app.js";
const secret = "ux-summary-test-secret-".repeat(3);
const url = process.env.TEST_DATABASE_URL;
if (!url) throw new Error("TEST_DATABASE_URL must identify a disposable database.");
test("versioned handover acknowledgement, concurrent updates and combined entry filters", async () => {
  const db = createPrismaClient(url), app = createApp(db, secret);
  const users: number[] = [];
  const suffix = randomUUID();
  try {
    for (let i = 0; i < 2; i++) users.push((await db.user.create({ data: { email: `${suffix}-${i}@example.com`, name: `Reader ${i}`, password: "unused" } })).id);
    const auth = users.map(id => `Bearer ${jwt.sign({ id }, secret, { expiresIn: "1h" })}`);
    const get = (path: string, who = 0) => request(app).get(path).set("Authorization", auth[who]!);
    const post = (path: string, body: object, who = 0) => request(app).post(path).set("Authorization", auth[who]!).send(body);
    await request(app).get("/operations/summary").expect(401);
    await request(app).post("/operations/summary/read").send({ revision: 0 }).expect(401);
    const initial = await get("/operations/summary").expect(200);
    assert.deepEqual(initial.body.equipment.map((item: any) => item.code), ["GT1", "GT2", "ST"]);
    await post("/operations/summary/read", { revision: initial.body.revision }).expect(409);
    const shift = await post("/shifts/start", {}).expect(201);
    const task = await post("/operations/entries", { kind: "TASK", priority: "HIGH", title: `Pump 100% ${suffix}`, description: "Kontrol edilecek", equipmentCode: "GT1" }).expect(201);
    const before = (await get("/operations/summary").expect(200)).body;
    assert.ok(before.counts.TASK >= 1);
    assert.ok(before.tasks.some((item: any) => item.id === task.body.id && item.description === "Kontrol edilecek"));
    assert.ok(before.tasks.length <= 5); assert.ok(before.valves.length <= 5); assert.ok(before.important.some((item: any) => item.id === task.body.id));
    await post("/operations/entries", { kind: "NOTE", title: `Pump other ${suffix}`, description: "Genel bilgi", equipmentCode: "GT2" }, 1).expect(201);
    await post("/operations/summary/read", { revision: before.revision }).expect(409);
    const latest = (await get("/operations/summary").expect(200)).body;
    const reads = await Promise.all([post("/operations/summary/read", { revision: latest.revision, userId: users[1] }), post("/operations/summary/read", { revision: latest.revision })]);
    assert.deepEqual(reads.map(r => r.status), [200, 200]); assert.equal(reads[0]!.body.id, reads[1]!.body.id);
    const saved = await db.handoverRead.findUniqueOrThrow({ where: { id: reads[0]!.body.id } });
    assert.equal(saved.userId, users[0]); assert.equal(saved.shiftId, shift.body.id);
    assert.equal((saved.snapshot as any).revision, latest.revision);
    assert.equal((await get("/operations/summary")).body.receipt.revision, latest.revision);
    const unit = latest.equipment[0];
    await request(app).put(`/operations/equipment/${unit.code}`).set("Authorization", auth[1]!).send({ status: "MAINTENANCE", note: "Maintenance", version: unit.version }).expect(200);
    await post("/operations/summary/read", { revision: latest.revision }).expect(409);
    const snapshot = (await get("/operations/summary")).body;
    const race = await Promise.all([post("/operations/summary/read", { revision: snapshot.revision }), post("/operations/entries", { kind: "EVENT", title: `Race ${suffix}`, description: "Updated" }, 1)]);
    assert.ok([200, 409].includes(race[0]!.status)); assert.equal(race[1]!.status, 201);
    if (race[0]!.status === 200) assert.equal(race[0]!.body.revision, snapshot.revision);
    const afterRace = (await get("/operations/summary")).body;
    assert.ok(afterRace.revision > snapshot.revision);
    assert.notEqual(afterRace.receipt?.revision, afterRace.revision);
    const literal = await get(`/operations/entries?view=all&q=${encodeURIComponent(`pump 100% ${suffix}`)}`).expect(200);
    assert.deepEqual(literal.body.items.map((item: any) => item.id), [task.body.id]);
    await post(`/operations/entries/${task.body.id}/close`, { closeNote: "Tamamlandı" }).expect(200);
    const closedSummary = (await get("/operations/summary").expect(200)).body;
    assert.equal(closedSummary.tasks.some((item: any) => item.id === task.body.id), false);
    const today = new Intl.DateTimeFormat("sv-SE", { timeZone: "Europe/Istanbul" }).format(new Date());
    const filters = new URLSearchParams({ view: "all", q: suffix, equipment: "GT1", kind: "TASK", status: "closed", from: today, to: today });
    const filtered = await get(`/operations/entries?${filters}`).expect(200);
    assert.equal(filtered.body.total, 1); assert.equal(filtered.body.items[0].equipmentCode, "GT1");
    filters.set("status", "open"); assert.equal((await get(`/operations/entries?${filters}`).expect(200)).body.total, 0);
    for (const invalid of ["q[]=bad", "from=2026-02-30", "from=2026-10-20&to=2026-10-19", "equipment=GT9", "kind=BAD", "status=BAD", "page=0", "unknown=1"]) await get(`/operations/entries?${invalid}`).expect(400);
    await db.operationEntry.createMany({ data: Array.from({ length: 24 }, (_, i) => ({ authorId: users[0]!, kind: "NOTE" as const, title: `Page ${suffix} ${i}`, description: "Test page", equipmentCode: "ST" })) });
    const second = await get(`/operations/entries?view=all&q=${encodeURIComponent(`Page ${suffix}`)}&equipment=ST&page=2`).expect(200);
    assert.equal(second.body.total, 24); assert.equal(second.body.items.length, 4);
    const valve = await post("/operations/entries", { kind: "VALVE", title: `Valve ${suffix}`, description: "Active valve note", equipmentCode: "ST" }).expect(201);
    await db.operationEntry.createMany({ data: Array.from({ length: 6 }, (_, i) => ({ authorId: users[0]!, kind: "TASK" as const, title: `Preview ${suffix} ${i}`, description: "Ongoing task" })) });
    const previews = (await get("/operations/summary").expect(200)).body;
    assert.equal(previews.tasks.length, 5); assert.ok(previews.counts.TASK >= 6);
    assert.ok(previews.valves.some((item: any) => item.id === valve.body.id && item.description === "Active valve note"));
    assert.equal(previews.tasks.some((item: any) => item.id === task.body.id), false);
    assert.ok(previews.tasks.every((item: any) => item.kind === "TASK"));
    assert.ok(previews.valves.every((item: any) => item.kind === "VALVE"));
    await post("/shifts/end", {}).expect(200); await post("/shifts/start", {}).expect(201);
    assert.equal((await get("/operations/summary")).body.receipt, null);
  } finally {
    await db.handoverRead.deleteMany({ where: { userId: { in: users } } });
    await db.operationEntry.deleteMany({ where: { authorId: { in: users } } });
    await db.equipmentChange.deleteMany({ where: { userId: { in: users } } });
    await db.shift.deleteMany({ where: { userId: { in: users } } });
    await db.user.deleteMany({ where: { id: { in: users } } });
    await db.$disconnect();
  }
});
